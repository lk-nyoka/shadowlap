ORDER = ["baseline", "shadow", "crash", "freeze", "sigstop", "flood", "attack"]
CLASS_COLORS = {
    "rear_lock_risk": "#D85A30",
    "over_battery": "#BA7517",
    "over_lap_cap": "#7F77DD",
    "over_motor": "#993556",
    "within_limits": "#1D9E75",
    "shadow_missing": "#888780",
}
CLASS_TEXT = {
    "rear_lock_risk": "asked the rear tyres for more braking than they could grip",
    "over_battery": "asked to charge harder than the battery could accept",
    "over_lap_cap": "kept harvesting after the lap's energy limit was used up",
    "over_motor": "asked a hot motor for more braking than it could safely give",
    "within_limits": "chose a different split that stayed within limits",
    "shadow_missing": "gave no answer (crashed, frozen or behind)",
}
DESCRIPTIONS = {
    "baseline": "v1 alone, no shadow. The timing reference.",
    "shadow": "v2 shadows a full lap.",
    "crash": "v2 crashes just after the first braking zone starts.",
    "freeze": "v2 hangs for 2 s as the car brakes for the first chicane.",
    "sigstop": "v2 is stopped from outside for 2 s, then resumed.",
    "flood": "v2 plus four CPU-burning threads on the shadow side.",
    "attack": "v2 tries to write to the brake actuator directly.",
}


def load(path):
    d = np.genfromtxt(path, delimiter=",", names=True, dtype=None, encoding="utf-8")
    return d


def png(fig):
    buf = io.BytesIO()
    fig.savefig(buf, format="png", dpi=130, bbox_inches="tight")
    plt.close(fig)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode()


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.grid(alpha=0.25, linewidth=0.5)
    ax.tick_params(labelsize=8)


def episodes(d):
    """Contiguous runs of the same non-agreeing class."""
    out = []
    cls = d["class"]
    i, n = 0, len(cls)
    while i < n:
        c = cls[i]
        if c in ("agree",):
            i += 1
            continue
        j = i
        while j + 1 < n and cls[j + 1] == c:
            j += 1
        seg = slice(i, j + 1)
        v = d["v_kmh"][seg]
        p1 = d["v1_regen"][seg] * v / 3.6 / 1e3
        p2 = d["v2_regen"][seg] * v / 3.6 / 1e3
        rear2 = d["v2_regen"][seg] + d["v2_friction"][seg]
        grip = d["f_rear_grip"][seg]
        k_lock = int(np.argmax(rear2 - grip))      # the worst single frame
        k_pow = int(np.argmax(p2 - p1))
        out.append(dict(
            cls=c, zone=int(d["zone"][i]), t0=float(d["t_lap"][i]), t1=float(d["t_lap"][j]),
            n=j - i + 1, soc0=float(d["soc"][i]), soc1=float(d["soc"][j]),
            harvest=float(d["lap_harvest_mj"][i]),
            p1=float(p1[k_pow]), p2=float(p2[k_pow]), soc_k=float(d["soc"][seg][k_pow]),
            t_pow=float(d["t_lap"][seg][k_pow]), p2max=float(p2.max()),
            v0=float(v[0]), v_lock=float(v[k_lock]), t_lock=float(d["t_lap"][seg][k_lock]),
            grip=float(grip[k_lock]), v2rear=float(rear2[k_lock]),
        ))
        i = j + 1
    keep = []
    for e in out:
        if e["cls"] == "shadow_missing" or (e["cls"] == "within_limits" and e["n"] >= 30) \
                or (e["cls"] not in ("within_limits", "shadow_missing") and e["n"] >= 5):
            keep.append(e)
    return keep


def sentence(e):
    z = f"braking zone {e['zone'] + 1}" if e["zone"] >= 0 else "outside braking"
    when = f"{e['t0']:.1f}-{e['t1']:.1f} s"
    if e["cls"] == "rear_lock_risk":
        return (f"In {z} ({when}, braking from {e['v0']:.0f} km/h) v2 asked for more rear braking than "
                f"the tyres could grip. Worst moment: at {e['t_lock']:.1f} s ({e['v_lock']:.0f} km/h) it asked "
                f"for {e['v2rear'] / 1e3:.1f} kN against a grip limit of about {e['grip'] / 1e3:.1f} kN. "
                f"v1 stayed under the limit. Under v2 the rear wheels would likely have locked.")
    if e["cls"] == "over_battery":
        return (f"In {z} ({when}) the battery was {e['soc0'] * 100:.0f}-{e['soc1'] * 100:.0f}% full. "
                f"A nearly full battery accepts less, so v1 eased off; v2 did not. Biggest gap: at "
                f"{e['t_pow']:.1f} s ({e['soc_k'] * 100:.0f}% full) v1 charged at {e['p1']:.0f} kW and v2 "
                f"asked for {e['p2']:.0f} kW.")
    if e["cls"] == "over_lap_cap":
        return (f"In {z} ({when}) the lap's harvest limit was already {e['harvest']:.2f} MJ used. "
                f"v1 stopped harvesting at the limit; v2 still asked for up to {e['p2max']:.0f} kW.")
    if e["cls"] == "over_motor":
        return (f"In {z} ({when}) the motor was hot enough to limit itself; v1 respected the limit, "
                f"v2 still asked for up to {e['p2max']:.0f} kW of motor braking.")
    if e["cls"] == "shadow_missing":
        return (f"From {e['t0']:.1f} s to {e['t1']:.1f} s ({e['n']} frames) v2 gave no answer. "
                f"v1 kept braking normally; these frames are marked as gaps, not as agreement.")
    return f"In {z} ({when}) v2 chose a different split that stayed within limits."


def md_to_html(md):
    """Tiny markdown subset for the analyst text: ## headings, - bullets, *italics*, paragraphs."""
    out, in_list = [], False
    for line in md.splitlines():
        t = html.escape(line.strip())
        t = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", t)
        t = re.sub(r"\*(.+?)\*", r"<i>\1</i>", t)
        if t.startswith(("- ", "* ")):
            if not in_list:
                out.append("<ul>"); in_list = True
            out.append(f"<li>{t[2:]}</li>"); continue
        if in_list:
            out.append("</ul>"); in_list = False
        if t.startswith("#"):
            out.append(f"<h3>{t.lstrip('#').strip()}</h3>")
        elif t == "---":
            out.append("<hr>")
        elif t:
            out.append(f"<p>{t}</p>")
    if in_list:
        out.append("</ul>")
    return "\n".join(out)


def lap_chart(d, title):
    t = d["t_lap"]
    fig, axes = plt.subplots(3, 1, figsize=(10, 6.6), sharex=True,
                             gridspec_kw=dict(height_ratios=[1.2, 1, 0.8]))
    ax = axes[0]
    ax.plot(t, d["v_kmh"], color="#444441", lw=1)
    for c, col in CLASS_COLORS.items():
        m = d["class"] == c
        if m.any():
            ax.scatter(t[m], d["v_kmh"][m], s=4, color=col, label=c.replace("_", " "), zorder=3)
    ax.set_ylabel("speed km/h", fontsize=8)
    ax.legend(fontsize=7, frameon=False, ncol=5, loc="lower left")
    ax.set_title(title, fontsize=10, loc="left")
    style(ax)

    ax = axes[1]
    v = d["v_kmh"] / 3.6
    ax.plot(t, d["v1_regen"] * v / 1e3, color="#0F6E56", lw=1.2, label="v1 harvesting (applied)")
    p2 = np.where(d["v2_present"] == 1, d["v2_regen"] * v / 1e3, np.nan)
    ax.plot(t, p2, color="#D85A30", lw=1, ls="--", label="v2 harvesting (proposed only)")
    ax.set_ylabel("motor kW", fontsize=8)
    ax.legend(fontsize=7, frameon=False, loc="upper left")
    style(ax)

    ax = axes[2]
    ax.plot(t, d["soc"] * 100, color="#185FA5", lw=1, label="battery %")
    ax.set_ylabel("battery %", fontsize=8)
    ax2 = ax.twinx()
    ax2.plot(t, d["lap_harvest_mj"], color="#7F77DD", lw=1, label="lap harvest MJ")
    ax2.set_ylabel("harvest MJ", fontsize=8)
    ax2.tick_params(labelsize=8)
    ax.set_xlabel("lap time, s", fontsize=8)
    style(ax)
    return png(fig)


def timing_chart(runs):
    names = [n for n in ORDER if n in runs and n != "attack"]
    fig, ax = plt.subplots(figsize=(10, 3.2))
    data = []
    for n in names:
        lat = runs[n]["v1_latency_us"]
        data.append(lat[lat >= 0])
    ax.boxplot(data, showfliers=True, flierprops=dict(markersize=2, alpha=0.4),
               medianprops=dict(color="#0F6E56"))
    ax.set_xticks(range(1, len(names) + 1), names)
    ax.set_yscale("log")
    ax.axhline(8000, color="#A32D2D", lw=0.8, ls="--")
    ax.text(0.55, 8000 * 1.15, "8 ms deadline", fontsize=7, color="#A32D2D")
    ax.set_ylabel("v1 frame-to-command, us", fontsize=8)
    ax.set_title("v1 timing in every scenario (log scale)", fontsize=10, loc="left")
    style(ax)
    return png(fig)


def fault_chart(d, name):
    t = d["t_lap"]
    fig, ax = plt.subplots(figsize=(10, 2.4))
    lat = d["v1_latency_us"]
    ax.plot(t, np.where(lat >= 0, lat, np.nan), color="#0F6E56", lw=0.6, label="v1 latency, us")
    miss = d["v2_present"] == 0
    if miss.any():
        ax.fill_between(t, 0, 1, where=miss, color="#888780", alpha=0.25,
                        transform=ax.get_xaxis_transform(), label="v2 not answering")
    ax.set_yscale("log")
    ax.set_ylabel("us", fontsize=8)
    ax.set_xlabel("lap time, s", fontsize=8)
    ax.legend(fontsize=7, frameon=False, loc="upper right")
    ax.set_title(f"{name}: v1 timing while the shadow misbehaves", fontsize=10, loc="left")
    style(ax)
    return png(fig)


def sweep_section(csv_path, summary_path):
    import csv as _csv
    rows = list(_csv.DictReader(open(csv_path)))
    summ = json.load(open(summary_path)) if os.path.exists(summary_path) else {}
    n = len(rows)

    def pct(rs, key):
        return 100.0 * sum(int(r[key]) > 0 for r in rs) / max(1, len(rs))

    grip_bins = [(0.85, 0.90), (0.90, 0.95), (0.95, 0.99), (0.99, 1.06)]
    air_bins = [(10, 20), (20, 30), (30, 40), (40, 46)]
    fig, axes = plt.subplots(1, 3, figsize=(10, 2.8))
    ax = axes[0]
    vals = [pct([r for r in rows if lo <= float(r["grip"]) < hi], "ep_lock_low_grip") for lo, hi in grip_bins]
    ax.bar([f"{lo:.2f}-{hi:.2f}" for lo, hi in grip_bins], vals, color="#D85A30")
    ax.set_title("Rear lock risk (low grip)\n% of laps, by track grip", fontsize=9, loc="left")
    ax = axes[1]
    vals = [pct([r for r in rows if lo <= float(r["ambient_c"]) < hi], "ep_over_motor") for lo, hi in air_bins]
    ax.bar([f"{lo}-{hi} C" for lo, hi in air_bins], vals, color="#993556")
    ax.set_title("Hot-motor overreach\n% of laps, by air temperature", fontsize=9, loc="left")
    ax = axes[2]
    laps = sorted({r["lap"] for r in rows}, key=int)
    vals = [pct([r for r in rows if r["lap"] == L], "ep_over_motor") for L in laps]
    ax.bar([f"lap {L}" for L in laps], vals, color="#993556")
    ax.set_title("Hot-motor overreach\n% of laps, by lap of the run", fontsize=9, loc="left")
    for ax in axes:
        ax.set_ylim(0, 105)
        style(ax)
        ax.tick_params(labelsize=7)
    img = png(fig)
    v1 = summ.get("v1_harvest_mj_per_lap", 0)
    v2 = summ.get("v2_safe_harvest_mj_per_lap", 0)
    return (f"<h2>Across {n} laps in changing conditions</h2>"
            f"<p>The fast sweep (<code>bbw_sweep</code>) replays the lap {n} times with the same car model and both brains, "
            f"varying the starting battery, air temperature and track grip. It answers how often v2 would be unsafe, "
            f"not just whether it was on one lap.</p>"
            f"<div class='finding'>v2 was unsafe for at least 50 ms on <b>{summ.get('laps_with_unsafe_v2', '?')}</b> of {n} laps. "
            f"It risked locking the rear wheels while the wings were still closing on {summ.get('laps_with_lock_while_wings_close', '?')} laps, "
            f"on a low-grip track on {summ.get('laps_with_lock_low_grip', '?')} laps, and over-asked a hot motor on "
            f"{summ.get('laps_with_hot_motor_overreach', '?')} laps.</div>"
            f"<img src='{img}' alt='sweep charts'>"
            f"<p>Energy per lap: v1 harvested {v1:.2f} MJ; using v2's choices only where they were safe would give {v2:.2f} MJ "
            f"({(v2 - v1) / v1 * 100 if v1 else 0:+.1f}%). v2's gain is small and its risks are not.</p>")


