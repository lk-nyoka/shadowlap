"""
Build one self-contained HTML report from the demo runs.

    python tools/report.py out            # reads out/<scenario>/compare.csv
    open out/report.html

Every number comes from the CSV files. The written findings are generated by
rules in this file (deterministic), so they can be checked line by line.
"""
