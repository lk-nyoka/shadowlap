def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir", nargs="?", default="out")
    a = ap.parse_args()

    runs, summaries = {}, {}
    for n in ORDER:
        f = os.path.join(a.outdir, n, "compare.csv")
        if os.path.exists(f):
            runs[n] = load(f)
            sj = os.path.join(a.outdir, n, "summary.json")
            summaries[n] = json.load(open(sj)) if os.path.exists(sj) else {}
    if not runs:
        raise SystemExit(f"no runs found under {a.outdir}/<scenario>/compare.csv")

    parts = [f"<!doctype html><html><head><meta charset='utf-8'><title>Shadow lap report</title>"
             f"<style>{CSS}</style></head><body><main>"]
    parts.append("<h1>Shadow lap report</h1><p class='sub'>Brake-by-wire controller v2 shadow-tested "
                 "against v1 on a replayed lap. v1 is in charge; v2 only proposes.</p>")

    # ---- headline table ----
    parts.append("<h2>Did v1 stay safe in every scenario?</h2><table><tr><th>Scenario</th><th>What happened</th>"
                 "<th>v1 deadline misses</th><th>plant overruns (host)</th><th>v1 p99 us</th><th>v1 max us</th><th>v2 gaps</th></tr>")
    for n in ORDER:
        if n not in runs:
            continue
        s = summaries.get(n, {})
        d = runs[n]
        lat = s.get("v1_latency_us", {})
        miss = s.get("v1_deadline_misses", 0)
        gaps = int((d["v2_present"] == 0).sum()) if n != "baseline" else 0
        if n in ("baseline", "attack"):
            gaps_s = "n/a"
        else:
            gaps_s = str(gaps)
        parts.append(f"<tr><td><b>{n}</b></td><td>{html.escape(DESCRIPTIONS.get(n, ''))}</td>"
                     f"<td class='num {'ok' if miss == 0 else 'bad'}'>{miss}</td>"
                     f"<td class='num'>{s.get('plant_overruns', 0)}</td>"
                     f"<td class='num'>{lat.get('p99', -1):.0f}</td><td class='num'>{lat.get('max', -1):.0f}</td>"
                     f"<td class='num'>{gaps_s}</td></tr>")
    parts.append("</table>")
    attack_log = os.path.join(a.outdir, "attack", "v2.log")
    if os.path.exists(attack_log):
        lines = [l.strip() for l in open(attack_log) if "ATTACK" in l]
        if lines:
            parts.append(f"<p><b>Attack result:</b> <code>{html.escape(lines[0])}</code></p>")
            if "NOT BLOCKED" in lines[0]:
                parts.append("<p>On this system nothing stopped the shadow from writing to the brakes. "
                             "Any v1 deadline misses in the attack row are the shadow's command "
                             "overwriting v1's. On QNX, run the attack with <code>V2_USER=qnxuser</code> "
                             "and with a security policy (docs/security-policy.md); it should be blocked.</p>")
    parts.append(f"<img src='{timing_chart(runs)}' alt='v1 latency per scenario'>")

    # ---- the disagreement story ----
    main_run = "shadow" if "shadow" in runs else next(iter(runs))
    d = runs[main_run]
    if main_run != "baseline":
        parts.append("<h2>Where v1 and v2 disagreed</h2>")
        parts.append(f"<img src='{lap_chart(d, 'Full lap: speed, harvesting and battery')}' alt='lap chart'>")
        counts = {c: int((d['class'] == c).sum()) for c in CLASS_COLORS}
        agree = int((d["class"] == "agree").sum())
        parts.append(f"<p>{agree} of {len(d)} frames agreed. "
                     + ", ".join(f"{v} frames {k.replace('_', ' ')}" for k, v in counts.items() if v) + ".</p>")
        for e in episodes(d):
            col = CLASS_COLORS.get(e["cls"], "#888780")
            parts.append(f"<div class='finding'><span class='tag' style='background:{col}'>"
                         f"{e['cls'].replace('_', ' ')}</span>{html.escape(sentence(e))}</div>")

    # ---- many laps (bbw_sweep) ----
    sw = os.path.join(a.outdir, "sweep", "laps.csv")
    if os.path.exists(sw):
        parts.append(sweep_section(sw, os.path.join(a.outdir, "sweep", "summary.json")))

    # ---- AI analyst ----
    am = os.path.join(a.outdir, main_run, "analyst.md")
    if os.path.exists(am):
        parts.append("<h2>AI analyst review</h2><div class='ai'>" + md_to_html(open(am).read()) + "</div>")

    # ---- fault scenarios ----
    for n in ("crash", "freeze", "sigstop", "flood"):
        if n in runs:
            parts.append(f"<h2>{n.capitalize()}</h2><p>{html.escape(DESCRIPTIONS[n])}</p>")
            parts.append(f"<img src='{fault_chart(runs[n], n)}' alt='{n} timing'>")
            for e in episodes(runs[n]):
                if e["cls"] == "shadow_missing":
                    parts.append(f"<div class='finding'>{html.escape(sentence(e))}</div>")

    parts.append("<h2>Read this before quoting numbers</h2><div class='note'><ul>"
                 "<li>Battery, motor and brake forces come from a small illustrative model "
                 "(<code>include/control.h</code>), not from a real car.</li>"
                 "<li>The lap supplies speed, throttle and a brake on/off flag. Public lap data is sampled a "
                 "few times per second and is interpolated to 100 Hz.</li>"
                 "<li>Shadow mode is open-loop: v2 always sees a battery shaped by v1's choices. The report "
                 "shows what v2 would have asked for in v1's world, not a full lap driven by v2.</li>"
                 "<li>Timing measured on this machine. Under QEMU, host scheduling adds noise; compare "
                 "scenarios from the same session rather than quoting absolute microseconds.</li>"
                 "</ul></div>")
    parts.append("</main></body></html>")

    out = os.path.join(a.outdir, "report.html")
    with open(out, "w") as fp:
        fp.write("\n".join(parts))
    print("wrote", out)


if __name__ == "__main__":
    main()
